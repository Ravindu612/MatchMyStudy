export const REPORT_REASON_MAX_LENGTH = 1000;

export function validateReportReason(
  value: string,
  emptyMessage = "Add a reason."
): { ok: true; reason: string } | { ok: false; message: string } {
  const reason = value.trim();

  if (!reason) {
    return { ok: false, message: emptyMessage };
  }

  if (reason.length > REPORT_REASON_MAX_LENGTH) {
    return {
      ok: false,
      message: `Reasons can be up to ${REPORT_REASON_MAX_LENGTH.toLocaleString("en-US")} characters.`,
    };
  }

  return { ok: true, reason };
}

export type ReportTargetType = "post" | "comment" | "profile" | "message";
export type ModerationContentStatus = "hidden" | "removed";
export type ReportDecision = "actioned" | "dismissed";

/**
 * Insert payload for public.reports.
 * status and reviewed_by have to match reports_insert or RLS rejects the row.
 * The id is generated by the caller so the insert does not use RETURNING.
 */
export function reportInsertRow(input: {
  id: string;
  reporterId: string;
  targetType: ReportTargetType;
  targetId: string;
  reason: string;
}) {
  return {
    id: input.id,
    reporter_id: input.reporterId,
    target_type: input.targetType,
    target_id: input.targetId,
    reason: input.reason,
    status: "open" as const,
    reviewed_by: null,
  };
}

/** Status-only patch. A follow-up select confirms it; the update itself does not use RETURNING. */
export function contentStatusPatch(status: ModerationContentStatus) {
  return { status };
}

export function reportDecisionPatch(input: {
  adminId: string;
  status: ReportDecision;
  note: string | null;
}) {
  return {
    status: input.status,
    reviewed_by: input.adminId,
    resolution_note: input.note,
  };
}

export function verificationPatch(isVerified: boolean) {
  return { is_verified: isVerified };
}

export type OpenReportPerson = {
  id: string;
  handle: string;
  displayName: string;
  isVerified: boolean;
};

export type OpenReportPost = {
  id: string;
  body: string;
  authorId: string;
  status: string;
  deletedAt: string | null;
};

export type OpenReportComment = {
  id: string;
  body: string;
  authorId: string;
  postId: string;
  status: string;
  deletedAt: string | null;
};

export type OpenReportMessage = {
  id: string;
  body: string;
  senderId: string | null;
  conversationId: string;
  deletedAt: string | null;
};

export type OpenReportSource = {
  id: string;
  reporterId: string | null;
  targetType: string;
  targetId: string;
  reason: string;
  createdAt: string;
};

export type OpenReportView = {
  id: string;
  createdAt: string;
  reason: string;
  reporterId: string | null;
  reporterName: string;
  reporterHandle: string | null;
  targetType: ReportTargetType;
  targetId: string;
  body: string | null;
  href: string | null;
  contentStatus: "active" | "hidden" | "removed" | "deleted" | null;
  profileId: string | null;
  profileName: string | null;
  profileHandle: string | null;
  isVerified: boolean | null;
};

export function assembleOpenReports(input: {
  reports: OpenReportSource[];
  people: OpenReportPerson[];
  posts: OpenReportPost[];
  comments: OpenReportComment[];
  messages: OpenReportMessage[];
}): OpenReportView[] {
  const people = new Map(input.people.map((person) => [person.id, person]));
  const posts = new Map(input.posts.map((post) => [post.id, post]));
  const comments = new Map(input.comments.map((comment) => [comment.id, comment]));
  const messages = new Map(input.messages.map((message) => [message.id, message]));

  return input.reports.flatMap((report) => {
    const targetType = reportTarget(report.targetType);

    if (!targetType) {
      return [];
    }

    const reporter = report.reporterId ? people.get(report.reporterId) : undefined;
    const base = {
      id: report.id,
      createdAt: report.createdAt,
      reason: report.reason,
      reporterId: report.reporterId,
      reporterName: reporter?.displayName ?? (report.reporterId ? "Member" : "Deleted user"),
      reporterHandle: reporter?.handle ?? null,
      targetType,
      targetId: report.targetId,
    };

    if (targetType === "post") {
      const post = posts.get(report.targetId);
      const author = post ? people.get(post.authorId) : undefined;

      return [
        {
          ...base,
          body: post?.body ?? null,
          href: post ? `/post/${post.id}` : null,
          contentStatus: post ? contentState(post.status, post.deletedAt) : "deleted",
          profileId: post?.authorId ?? null,
          profileName: author?.displayName ?? null,
          profileHandle: author?.handle ?? null,
          isVerified: author ? author.isVerified : null,
        },
      ];
    }

    if (targetType === "comment") {
      const comment = comments.get(report.targetId);
      const author = comment ? people.get(comment.authorId) : undefined;

      return [
        {
          ...base,
          body: comment?.body ?? null,
          href: comment ? `/post/${comment.postId}` : null,
          contentStatus: comment ? contentState(comment.status, comment.deletedAt) : "deleted",
          profileId: comment?.authorId ?? null,
          profileName: author?.displayName ?? null,
          profileHandle: author?.handle ?? null,
          isVerified: author ? author.isVerified : null,
        },
      ];
    }

    if (targetType === "message") {
      const message = messages.get(report.targetId);
      const sender = message?.senderId ? people.get(message.senderId) : undefined;

      return [
        {
          ...base,
          body: message?.body ?? null,
          href: message ? `/messages/${message.conversationId}` : null,
          contentStatus: message ? (message.deletedAt ? "deleted" : "active") : "deleted",
          profileId: message?.senderId ?? null,
          profileName:
            sender?.displayName ?? (message && message.senderId === null ? "Deleted user" : null),
          profileHandle: sender?.handle ?? null,
          isVerified: sender ? sender.isVerified : null,
        },
      ];
    }

    const profile = people.get(report.targetId);

    return [
      {
        ...base,
        body: null,
        href: profile ? `/u/${encodeURIComponent(profile.handle)}` : null,
        contentStatus: null,
        profileId: report.targetId,
        profileName: profile?.displayName ?? "Deleted user",
        profileHandle: profile?.handle ?? null,
        isVerified: profile ? profile.isVerified : null,
      },
    ];
  });
}

function reportTarget(value: string): ReportTargetType | null {
  if (value === "post" || value === "comment" || value === "profile" || value === "message") {
    return value;
  }

  return null;
}

function contentState(
  status: string,
  deletedAt: string | null
): OpenReportView["contentStatus"] {
  if (deletedAt) {
    return "deleted";
  }

  if (status === "active" || status === "hidden" || status === "removed") {
    return status;
  }

  return null;
}
