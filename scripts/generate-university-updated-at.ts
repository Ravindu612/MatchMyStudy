/*
 * Regenerates data/universityUpdatedAt.ts from git history.
 *
 *   npx tsx scripts/generate-university-updated-at.ts
 *
 * Run it on an up-to-date main after a program batch is merged, then
 * commit the result. For each university the date is when content for
 * it last landed on main:
 *   - universities with program files: the latest main commit that
 *     touched one of the files in data/programs/ holding its programs;
 *   - universities without programs: the main commit that added the
 *     university's entry in data/universities/.
 * Dates come from `git log --first-parent` (merge dates on main), so
 * they reflect when the change went live, not when a branch was started.
 * It needs full git history (not a shallow clone), which is why the
 * result is committed instead of computed during the Vercel build.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(__dirname, "..");
const REF = process.argv[2] ?? "HEAD";

function git(args: string[]) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim();
}

function walk(dir: string): string[] {
  return readdirSync(join(ROOT, dir)).flatMap((name) => {
    const rel = join(dir, name);
    return statSync(join(ROOT, rel)).isDirectory()
      ? walk(rel)
      : rel.endsWith(".ts") && !rel.endsWith("index.ts")
        ? [rel]
        : [];
  });
}

function lastMainDate(path: string) {
  return git(["log", "-1", "--first-parent", "--format=%cs", REF, "--", path]);
}

const latestBySlug = new Map<string, string>();

for (const file of walk("data/programs")) {
  const text = readFileSync(join(ROOT, file), "utf8");
  const slugs = new Set(
    [...text.matchAll(/universitySlug:\s*"([^"]+)"/g)].map((m) => m[1])
  );
  if (slugs.size === 0) continue;
  const date = lastMainDate(file);
  if (!date) continue; // not committed yet
  for (const slug of slugs) {
    const prev = latestBySlug.get(slug);
    if (!prev || date > prev) latestBySlug.set(slug, date);
  }
}

for (const file of walk("data/universities")) {
  const text = readFileSync(join(ROOT, file), "utf8");
  for (const m of text.matchAll(/^\s*slug:\s*"([^"]+)"/gm)) {
    const slug = m[1];
    if (latestBySlug.has(slug)) continue;
    // Oldest first-parent commit that changed the number of times this
    // slug appears in the file = when the entry was added on main.
    const dates = git([
      "log", "--first-parent", "--format=%cs", `-S${m[0].trim()}`, REF, "--", file,
    ]).split("\n").filter(Boolean);
    const added = dates[dates.length - 1];
    if (added) latestBySlug.set(slug, added);
  }
}

const entries = [...latestBySlug.entries()].sort(([a], [b]) => a.localeCompare(b));
const out = `// Generated by scripts/generate-university-updated-at.ts. Do not edit by hand;
// re-run the script after merging a program batch (see the script for how
// dates are chosen). A \`updatedAt\` set directly on a university entry in
// data/universities/ takes precedence over this map.
//
// Used for <lastmod> of /universities/<slug> and that university's
// /programs/<slug> pages in app/sitemap.ts.

export const universityUpdatedAt: Record<string, string> = {
${entries.map(([slug, date]) => `  ${JSON.stringify(slug)}: "${date}",`).join("\n")}
};
`;
writeFileSync(join(ROOT, "data/universityUpdatedAt.ts"), out);
console.log(`Wrote ${entries.length} dates to data/universityUpdatedAt.ts`);
